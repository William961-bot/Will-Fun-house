"""Pack the MUGEN sprites of Ella (by Aiduzzi) into assets/ella/mugen.png (+ mugen-alt.png, the second palette) and write
src/ella-atlas.js, the clip table render-ella.js reads. Local only: assets/ella/ is git-ignored.
Usage: python tools/pack-ella-mugen.py <folder with ella.sff, ella.air, ella*.act>"""
import sys, os, json
sys.path.insert(0, os.path.dirname(__file__))
import mugen_sff as m
from PIL import Image

SCALE = 1.7
SIZE, COLS, ANCHOR = 320, 12, (160, 260)
ROOT = os.path.join(os.path.dirname(__file__), '..')
folder = sys.argv[1]
sp = m.read_sff(os.path.join(folder, 'ella.sff')); air = m.read_air(os.path.join(folder, 'ella.air'))
PALETTES = {'mugen.png': 'ellaa.act', 'mugen-alt.png': sys.argv[2] if len(sys.argv) > 2 else 'ellac.act'}

# key: (Mugen action, frames sampled, game tick the hit lands, game ticks in the move). Attack clips are time-warped
# so the Mugen strike frame lands on the Hoodratz startup; render-ella.js then just plays stateFrame / total ticks.
CLIPS = dict(
    idle=(0, 24, None, None), walk=(20, 8, None, None), backward=(21, 8, None, None), dash=(100, 8, None, None),
    backdash=(105, 6, None, None), air=(41, 8, None, None), land=(47, 3, None, None), crouch=(11, 4, None, None),
    block=(130, 1, None, None), light=(200, 8, 5, 18), medium=(210, 10, 9, 26), low=(400, 8, 7, 23),
    lowMedium=(410, 8, 11, 31), heavy=(240, 12, 28, 57), overhead=(310, 10, 14, 32), airLight=(600, 8, 6, 17),
    airMedium=(610, 8, 7, 21), airHeavy=(640, 10, 12, 31), grab=(811, 10, None, None), grabMiss=(810, 4, None, None),
    hit=(5000, 4, None, None), ko=(5120, 8, None, None), escape=(5200, 8, None, None),
    piccion=(1000, 12, None, None), nautilus=(1210, 10, 8, 44), oriuken=(1100, 8, 7, 38),
)

def frame_at(frames, tick):
    t = 0
    for f in frames:
        t += max(1, f['t'])
        if tick < t: return f
    return frames[-1]

def cell_for(f, pal):
    cell = Image.new('RGBA', (SIZE, SIZE)); s = sp[(f['grp'], f['idx'])]
    img = m.colorize(s, pal); img = img.resize((max(1, round(img.width * SCALE)), max(1, round(img.height * SCALE))), Image.NEAREST)
    ax = s['ax'] * SCALE
    if 'H' in f['flip']: img = img.transpose(Image.FLIP_LEFT_RIGHT); ax = img.width - ax
    if 'V' in f['flip']: img = img.transpose(Image.FLIP_TOP_BOTTOM)
    x, y = round(ANCHOR[0] + f['x'] * SCALE - ax), round(ANCHOR[1] + (f['y'] - s['ay']) * SCALE)
    box = (max(0, -x), max(0, -y), min(img.width, SIZE - x), min(img.height, SIZE - y))
    if box[2] > box[0] and box[3] > box[1]: cell.alpha_composite(img.crop(box), (max(0, x), max(0, y)))
    return cell, x < 0 or y < 0 or x + img.width > SIZE or y + img.height > SIZE

# Layout and sampling are palette-independent, so work out which Mugen frame each atlas frame uses once.
layout, clips, n = [], {}, 0
for key, (action, count, contact, total) in CLIPS.items():
    frames = [f for f in air[action] if (f['grp'], f['idx']) in sp]
    span = sum(max(1, f['t']) for f in frames)
    hit_at = next((sum(max(1, g['t']) for g in frames[:i]) for i, f in enumerate(frames) if f['hit']), None)
    fm = hit_at / span if hit_at is not None else None
    at = min(.8, contact / total) if contact and total else None
    clips[key] = dict(start=n, count=count, ticks=span)
    for i in range(count):
        u = i / max(1, count - 1)
        if fm and at: u = fm * u / at if u < at else fm + (1 - fm) * (u - at) / (1 - at)
        layout.append(frame_at(frames, min(span - 1, u * (span - 1)))); n += 1

clipped = set()
for out_name, act in PALETTES.items():
    pal = m.read_act(os.path.join(folder, act))
    sheet = Image.new('RGBA', (COLS * SIZE, -(-n // COLS) * SIZE))
    for i, f in enumerate(layout):
        cell, over = cell_for(f, pal)
        if over: clipped.update(k for k, c in clips.items() if c['start'] <= i < c['start'] + c['count'])
        sheet.alpha_composite(cell, (i % COLS * SIZE, i // COLS * SIZE))
    sheet.save(os.path.join(ROOT, 'assets/ella', out_name), optimize=True)
    print(out_name, sheet.size)
print('frames', n, 'clipped clips:', sorted(clipped))

atlas = dict(size=SIZE, columns=COLS, anchor=list(ANCHOR), frames=n, clips=clips)
open(os.path.join(ROOT, 'src/ella-atlas.js'), 'w').write(
    '// Ella (MUGEN, by Aiduzzi) clip table. Generated by tools/pack-ella-mugen.py; the sheets in assets/ella/ stay local.\n'
    'const ELLA_ATLAS=' + json.dumps(atlas, separators=(',', ':')) + ';\n')
