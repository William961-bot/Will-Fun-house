// Turns a pose-tracking capture (image joints per frame) into stickman poses for the game.
// Usage: node tools/mocap-convert.cjs <capture.json> <clipName> <out.js>
// Keeps the video's joint ANGLES but the stickman's own limb LENGTHS, so every fighter keeps his proportions.
// Image y points down and so does game y (negative is up), so directions carry over unchanged; x is "forward".
const fs = require('fs');
const [, , input, name, output] = process.argv;
const cap = JSON.parse(fs.readFileSync(input, 'utf8'));
const J = Object.fromEntries(cap.joints.map((n, i) => [n, i]));
// Stickman bone lengths, matching STAND in render.js.
const BONE = { torso: 58, neck: 18, upper: 32, fore: 27, thigh: 38, shin: 38 };

const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const mid = (a, b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
const unit = v => { const l = Math.hypot(v[0], v[1]) || 1; return [v[0] / l, v[1] / l]; };
const along = (from, a, b, len) => { const d = unit(sub(b, a)); return [from[0] + d[0] * len, from[1] + d[1] * len]; };

// Light smoothing over neighbouring frames removes tracking jitter (the clip loops, so it wraps).
function smooth(frames) {
  return frames.map((f, i) => f.map((p, k) => {
    const a = frames[(i - 1 + frames.length) % frames.length][k], c = frames[(i + 1) % frames.length][k];
    return [(a[0] + 2 * p[0] + c[0]) / 4, (a[1] + 2 * p[1] + c[1]) / 4];
  }));
}
let frames = cap.frames.map(f => f.map(p => [p[0], p[1]]));
// Tracking tools often repeat the final frame; drop exact duplicates at the end so the loop doesn't stall.
while (frames.length > 2 && JSON.stringify(frames.at(-1)) === JSON.stringify(frames.at(-2))) frames.pop();
frames = smooth(frames);

const hipMid = f => mid(f[J.hipL], f[J.hipR]);
const meanHipX = frames.reduce((s, f) => s + hipMid(f)[0], 0) / frames.length;
const torsoPx = frames.reduce((s, f) => s + Math.hypot(...sub(mid(f[J.shoulderL], f[J.shoulderR]), hipMid(f))), 0) / frames.length;
const scale = BONE.torso / torsoPx;

// The tracked person faces the camera. The screen-right side (their left) becomes the stickman's front limbs.
const poses = frames.map(f => {
  const hipImg = hipMid(f), shoulders = mid(f[J.shoulderL], f[J.shoulderR]), ears = mid(f[J.earL], f[J.earR]);
  const hip = [(hipImg[0] - meanHipX) * scale, 0];
  const neck = along(hip, hipImg, shoulders, BONE.torso);
  const head = along(neck, shoulders, ears, BONE.neck);
  const limb = (root, a, b, c, l1, l2) => { const j = along(root, f[a], f[b], l1); return [j, along(j, f[b], f[c], l2)]; };
  const [eF, hF] = limb(neck, J.shoulderL, J.elbowL, J.wristL, BONE.upper, BONE.fore);
  const [eB, hB] = limb(neck, J.shoulderR, J.elbowR, J.wristR, BONE.upper, BONE.fore);
  const [kF, fF] = limb(hip, J.hipL, J.kneeL, J.ankleL, BONE.thigh, BONE.shin);
  const [kB, fB] = limb(hip, J.hipR, J.kneeR, J.ankleR, BONE.thigh, BONE.shin);
  const p = { head, neck, hip, eF, hF, eB, hB, kF, fF, kB, fB };
  // Plant the lower foot on the floor (y = 0) every frame, so the dance never floats or sinks.
  const drop = -Math.max(fF[1], fB[1]);
  for (const k in p) p[k] = [Math.round(p[k][0] * 10) / 10, Math.round((p[k][1] + drop) * 10) / 10];
  return p;
});

const header = `// Generated by tools/mocap-convert.cjs from ${cap.source} (${poses.length} frames at ${1000 / cap.frameMs} fps). Don't edit by hand.\n`;
const body = `MOCAP_CLIPS[${JSON.stringify(name)}] = { fps: ${1000 / cap.frameMs}, frames: ${JSON.stringify(poses)} };\n`;
fs.writeFileSync(output, header + body);
console.log(`${name}: ${poses.length} frames, scale ${scale.toFixed(3)}, wrote ${output}`);
