"""Godot 4 target adapter: writes a project that runs the port spec, and runs it headless.

Layout written into OUT:
    project.godot
    port/character.json   the port spec (from the UCS only) with its assumptions and manual items
    port/character.gd     generic runtime executing the spec, one source tick per step
    port/replay.gd        replays a scenario and writes the port's trace
    port/asset_check.gd   loads assets/character.glb at runtime and reports skeleton and animations
    assets/character.glb  the character exported from verified assets (when given)
    COMPATIBILITY.json    the compatibility report"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

RUNTIME = Path(__file__).with_name("godot_runtime")


def write_project(out: Path, spec: dict, compat: dict, glb: bytes | None = None) -> Path:
    out = Path(out)
    (out / "port").mkdir(parents=True, exist_ok=True)
    tick = round(spec["tick_rate"]) if spec.get("tick_rate") else 60
    (out / "project.godot").write_text(
        "; generated by chardecomp from a UCS document\n"
        "config_version=5\n\n[application]\n"
        f"config/name=\"{spec.get('character') or 'character'} (chardecomp port)\"\n\n"
        f"[physics]\ncommon/physics_ticks_per_second={tick}\n", encoding="utf-8")
    (out / "port" / "character.json").write_text(json.dumps(spec, indent=1) + "\n", encoding="utf-8")
    for f in ("character.gd", "replay.gd", "asset_check.gd"):
        shutil.copy(RUNTIME / f, out / "port" / f)
    (out / "COMPATIBILITY.json").write_text(json.dumps(compat, indent=1) + "\n", encoding="utf-8")
    if glb is not None:
        (out / "assets").mkdir(exist_ok=True)
        (out / "assets" / "character.glb").write_bytes(glb)
    return out


def godot_binary() -> str:
    exe = os.environ.get("GODOT_BIN") or shutil.which("godot4") or shutil.which("godot")
    if not exe:
        raise FileNotFoundError("Godot 4 not found: set GODOT_BIN or put godot on PATH")
    return exe


def _run(project: Path, script: str, args: list[str], timeout: float = 120) -> None:
    res = subprocess.run([godot_binary(), "--headless", "--path", str(project), "--script", script, "--", *args],
                         capture_output=True, text=True, timeout=timeout)
    errors = [ln for ln in (res.stdout + res.stderr).splitlines() if "ERROR" in ln or "SCRIPT ERROR" in ln]
    if res.returncode != 0 or errors:
        raise RuntimeError(f"godot {script} failed ({res.returncode}): " + "\n".join(errors[:10] or [res.stderr[-2000:]]))


def replay(project: Path, scenario: dict, work_dir: Path) -> list[dict]:
    work_dir.mkdir(parents=True, exist_ok=True)
    scen, out = work_dir / "scenario.json", work_dir / "godot_trace.json"
    scen.write_text(json.dumps(scenario), encoding="utf-8")
    _run(project, "res://port/replay.gd", [str(scen), str(out)])
    return json.loads(out.read_text(encoding="utf-8"))


def asset_check(project: Path, work_dir: Path) -> dict:
    work_dir.mkdir(parents=True, exist_ok=True)
    out = work_dir / "asset_check.json"
    _run(project, "res://port/asset_check.gd", [str(out)])
    return json.loads(out.read_text(encoding="utf-8"))
