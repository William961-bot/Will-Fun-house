"""Port report: compatibility, assumptions, manual items, asset check and per-scenario trace comparison."""

from __future__ import annotations


def explain(field: str, spec: dict, result: dict) -> str | None:
    """A verified account of a differing field, or None (unexplained). Each explanation is tested against the
    mismatching ticks, not assumed."""
    rows = result["fields"][field]["ticks"]
    walk = [a["to"] for a in spec["actions"].values() if a["kind"] == "walk" and str(a["to"]) not in spec["timed"]]
    if field == "character.state" and walk and all(tgt == walk[0] and src != walk[0] for _, src, tgt in rows):
        return (f"the port is still in the walk state ({walk[0]}) where the source has left it: the walk exit rule is "
                "not in the UCS (manual item)")
    if field == "character.hitbox_active" and {tk for tk, _, _ in rows} <= set(result.get("hit_ticks", [])):
        return ("differs only on ticks where a hit connected: the UCS frame data was measured on whiffs, and on a "
                "hit the source's hitbox is off in the frame it connects")
    return None


def markdown(spec: dict, compat: dict, assets: dict | None, results: dict[str, dict]) -> str:
    L = [f"# Port of {spec.get('character') or 'the character'} to {compat['target']}", "",
         "Generated by chardecomp from the UCS only. Every number in `port/character.json` is a UCS fact; the "
         "rules below the facts are the assumptions listed here, tested by replaying source recordings.", "",
         "## Compatibility", "", "| category | items |", "|---|---|"]
    for cat, n in compat["counts"].items():
        L.append(f"| {cat} | {n} |")
    L += ["", "| category | item | why |", "|---|---|---|"]
    L += [f"| {i['category']} | {i['item']} | {i['why']} |" for i in compat["items"]]
    L += ["", "## Assumptions", ""] + [f"- {a}" for a in spec["assumptions"]]
    L += ["", "## Manual items", ""] + ([f"- {m}" for m in spec["manual"]] or ["- none"])
    if spec["missing"]:
        L += ["", "## Missing from the UCS (the port cannot implement these)", ""] + [f"- {m}" for m in spec["missing"]]
    if assets is not None:
        L += ["", "## Assets in the target", "",
              f"- load error code: {assets.get('error')}",
              f"- bones: {[b['name'] for b in assets.get('bones', [])]}",
              f"- animations: {[(a['name'], round(a['length'], 4)) for a in assets.get('animations', [])]}",
              f"- meshes: {assets.get('meshes')}"]
    L += ["", "## Replays", "", "| recording | ticks | matching fields | differing fields |", "|---|---|---|---|"]
    unexplained = []
    for name, r in results.items():
        diff = []
        for k in r["differing"]:
            why = explain(k, spec, r)
            diff.append(f"{k} ({r['fields'][k]['mismatches']} ticks{'; ' + why if why else '; UNEXPLAINED'})")
            if not why:
                unexplained.append(f"{name}: {k}")
        L.append(f"| {name} | {r['ticks']} | {len(r['matching'])} | {'; '.join(diff) or 'none'} |")
    L += ["", "Unexplained differences: " + (", ".join(unexplained) if unexplained else "none") + "."]
    return "\n".join(L) + "\n"


def unexplained(spec: dict, results: dict[str, dict]) -> list[str]:
    return [f"{n}: {k}" for n, r in results.items() for k in r["differing"] if not explain(k, spec, r)]
